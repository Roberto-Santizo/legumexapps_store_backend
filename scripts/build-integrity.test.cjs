const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { run } = require('./build-integrity.cjs')

test('migration and administrative inputs participate in the build seal',async t=>{
 const base=await fs.mkdtemp(path.join(os.tmpdir(),'legumex-build-test-'))
 if(path.dirname(path.resolve(base))!==path.resolve(os.tmpdir()) || !path.basename(base).startsWith('legumex-build-test-')) throw new Error('Unsafe test path')
 t.after(()=>fs.rm(base,{recursive:true,force:true}))
 for(const folder of ['src','dist','scripts','migrations']) await fs.mkdir(path.join(base,folder))
 for(const name of ['src/index.ts','dist/index.js','tsconfig.json','tsconfig.build.json','package.json','package-lock.json','scripts/build-integrity.cjs','scripts/bootstrap.cjs','scripts/production-release.cjs','scripts/rebuild-public.sql','migrations/202610110001_initial_schema.sql']) await fs.writeFile(path.join(base,name),'synthetic')
 await run('stamp',base)
 for(const name of ['scripts/bootstrap.cjs','scripts/production-release.cjs','scripts/rebuild-public.sql','migrations/202610110001_initial_schema.sql']) {
  await fs.appendFile(path.join(base,name),' changed')
  await assert.rejects(run('verify',base))
  await run('stamp',base)
 }
})
test('missing stamp, changed sources, config and outputs block; current build passes without executing it', async t => {
    const base = await fs.mkdtemp(path.join(os.tmpdir(), 'legumex-build-test-'))
    if (path.dirname(path.resolve(base)) !== path.resolve(os.tmpdir()) || !path.basename(base).startsWith('legumex-build-test-')) throw new Error('Unsafe test path')
    t.after(() => fs.rm(base, { recursive: true, force: true }))
    for (const folder of ['src', 'dist', 'scripts']) await fs.mkdir(path.join(base, folder))
    const files = ['src/index.ts', 'dist/index.js', 'tsconfig.json', 'tsconfig.build.json', 'package.json', 'package-lock.json', 'scripts/build-integrity.cjs']
    for (const name of files) await fs.writeFile(path.join(base, name), 'throw new Error("must never execute")')
    await assert.rejects(run('verify', base))
    await run('stamp', base)
    await run('verify', base)
    for (const name of files) {
        await fs.appendFile(path.join(base, name), ' changed')
        await assert.rejects(run('verify', base))
        await run('stamp', base)
        await run('verify', base)
    }
    await fs.writeFile(path.join(base, 'src/added.ts'), 'new source')
    await assert.rejects(run('verify', base))
})

test('translation JSON and arbitrary output additions, changes and removals invalidate prestart verification', async t => {
    const base = await fs.mkdtemp(path.join(os.tmpdir(), 'legumex-build-test-'))
    if (path.dirname(path.resolve(base)) !== path.resolve(os.tmpdir()) || !path.basename(base).startsWith('legumex-build-test-')) throw new Error('Unsafe test path')
    t.after(() => fs.rm(base, { recursive: true, force: true }))
    for (const folder of ['src/locales/es', 'dist/locales/es', 'scripts']) await fs.mkdir(path.join(base, folder), { recursive: true })
    for (const name of ['src/index.ts', 'dist/index.js', 'tsconfig.json', 'tsconfig.build.json', 'package.json', 'package-lock.json', 'scripts/build-integrity.cjs']) await fs.writeFile(path.join(base, name), 'never execute')
    const source = path.join(base, 'src/locales/es/translation.json')
    const emitted = path.join(base, 'dist/locales/es/translation.json')
    await fs.writeFile(source, '{"label":"original"}')
    await fs.writeFile(emitted, '{"label":"original"}')
    await run('stamp', base)
    await run('verify', base) // manifest must not hash itself
    await fs.writeFile(source, '{"label":"changed"}')
    await assert.rejects(run('verify', base), /Stale build/)
    await run('stamp', base)
    await fs.writeFile(emitted, '{"label":"changed"}')
    await assert.rejects(run('verify', base), /Stale build/)
    await run('stamp', base)
    const added = path.join(base, 'dist/locales/es/added.json')
    await fs.writeFile(added, '{}')
    await assert.rejects(run('verify', base), /Stale build/)
    await run('stamp', base)
    await fs.unlink(emitted)
    await assert.rejects(run('verify', base), /Stale build/)
    await run('stamp', base)
    await fs.writeFile(path.join(base, 'dist/asset.binary'), Buffer.from([0, 1, 2]))
    await assert.rejects(run('verify', base), /Stale build/)
    await run('stamp', base)
    for (const name of ['dist/editor.tmp', 'dist/editor.swp', 'dist/editor~', 'src/editor.temp']) await fs.writeFile(path.join(base, name), 'temporary')
    await run('verify', base)
    await fs.mkdir(path.join(base, 'dist/.cache'))
    await fs.writeFile(path.join(base, 'dist/.cache/temporary.json'), '{}')
    await run('verify', base)
})
